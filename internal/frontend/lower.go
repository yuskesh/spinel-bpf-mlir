func Lower(res *Result) (string, error) {
	var b strings.Builder
	b.WriteString("// Code generated by spinelbpf. DO NOT EDIT.\n")
	b.WriteString(version.MLIRLine())
	for _, f := range res.Funcs {
		if err := lowerFunc(&b, f); err != nil {
			return "", err
		}
	}
	for _, p := range res.Programs {
		if err := lowerProgram(&b, p); err != nil {
			return "", err
		}
	}
	text := b.String()
	if err := VerifyWorld(text); err != nil {
		return "", err
	}
	return text, nil
}

func mapType(m *MapDecl) string {
	return fmt.Sprintf(`!ebpf.map<%q, %s, %s>`, m.MapKind(), keyType(m), valueType(m))
}

func keyType(m *MapDecl) string {
	switch {
	case m.KeyRecord != nil:
		return m.KeyRecord.MLIRType()
	case m.IsArray(), m.IsDevmap(), m.Kind == "sockmap":
		return "i32"
	}
	return fmt.Sprintf("i%d", m.KeyBits)
}

func valueType(m *MapDecl) string {
	if m.Record != nil {
		return m.Record.MLIRType()
	}
	return fmt.Sprintf("i%d", m.ValueBits)
}

func loc(p Pos) string { return fmt.Sprintf(`loc(%q:%d:%d)`, p.File, p.Line, p.Col) }

type ssaVal struct {
	name string
	ty   string
}

type borrow struct {
	name string
	bits int
}

type lowerer struct {
	kind   string
	b      *strings.Builder
	n      *int
	maps   map[*MapDecl]string
	indent string
	env    map[string]ssaVal
	refs   map[string]borrow
	wins   map[string]borrow
	loops  [][]string
	fired  string
	narrow map[string]string
}

func (l *lowerer) val() string {
	v := fmt.Sprintf("%%v%d", *l.n)
	*l.n++
	return v
}

func (l *lowerer) emit(format string, args ...any) {
	l.b.WriteString(l.indent)
	fmt.Fprintf(l.b, format, args...)
	l.b.WriteByte('\n')
}

func lowerProgram(b *strings.Builder, p *Program) error {
	if p.Verdict == "" {
		return fmt.Errorf("internal: program %s has no verdict", p.Name)
	}
	n := 0
	l := &lowerer{b: b, n: &n, maps: map[*MapDecl]string{}, indent: "  ", env: map[string]ssaVal{}, refs: map[string]borrow{}, wins: map[string]borrow{}, kind: p.Kind}
	var syms, params []string
	for i, m := range p.Maps {
		syms = append(syms, "@"+m.Name)
		l.maps[m] = fmt.Sprintf("%%m%d", i)
		params = append(params, fmt.Sprintf("%%m%d: %s", i, mapType(m)))
	}
	fmt.Fprintf(b, "ebpf.program @%s %q", p.Name, p.Kind)
	if p.Target != "" {
		fmt.Fprintf(b, " attach %q", p.Target)
	}
	if p.Kind == "kprobe" || p.Kind == "uprobe" || p.Kind == "kretprobe" || p.Kind == "uretprobe" || p.Kind == "ksyscall" {
		b.WriteString(` arch "x86_64"`)
	}
	if len(syms) > 0 {
		fmt.Fprintf(b, " maps [%s]", strings.Join(syms, ", "))
	}
	b.WriteString(" {\n")
	fmt.Fprintf(b, "^bb0(%s):\n", strings.Join(append([]string{fmt.Sprintf("%%ctx: !ebpf.ctx<%q>", p.Kind)}, params...), ", "))
	if err := l.stmts(p.Body); err != nil {
		return err
	}
	if fmodUses(p) {
		if err := l.lowerFmodReturn(p); err != nil {
			return err
		}
	} else if p.GuardVerdict != "" {
		gv, v := p.GuardVerdict, p.Verdict
		if p.Kind == "socket_filter" && mutation("sf-swap-verdict") {
			gv, v = v, gv
		}
		if p.Kind == "cgroup_skb" && mutation("cg-swap-verdict") {
			gv, v = v, gv
		}
		if p.Kind == "netfilter" && mutation("nf-swap-verdict") {
			gv, v = v, gv
		}
		fmt.Fprintf(b, "  ebpf.verdict.if %s %q else %q %s\n", l.fired, gv, v, loc(p.VerdictPos))
	} else if p.RedirMap != nil {
		k, err := l.expr(p.RedirKey)
		if err != nil {
			return err
		}
		k32 := l.val()
		l.emit("%s = arith.trunci %s : i64 to i32 %s", k32, k.name, loc(p.VerdictPos))
		fb := p.Verdict
		if mutation("redirect-fallback-drop") {
			fb = "drop"
		}
		fmt.Fprintf(b, "  ebpf.redirect_map %s[%s] : %s, i32 fallback %q %s\n", l.maps[p.RedirMap], k32, mapType(p.RedirMap), fb, loc(p.VerdictPos))
	} else {
		fmt.Fprintf(b, "  ebpf.verdict %q %s\n", p.Verdict, loc(p.VerdictPos))
	}
	fmt.Fprintf(b, "} %s\n", loc(p.Pos))
	return nil
}

func (l *lowerer) expr(e *Expr) (ssaVal, error) {
	switch e.Kind {
	case "lit":
		v := l.val()
		l.emit("%s = arith.constant %s : i64 %s", v, e.Lit, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "blit":
		v := l.val()
		l.emit("%s = arith.constant %v %s", v, e.B, loc(e.Pos))
		return ssaVal{v, "i1"}, nil
	case "var":
		s, ok := l.env[e.Var]
		if !ok {
			return ssaVal{}, fmt.Errorf("internal: local %s has no value at %s", e.Var, e.Pos)
		}
		return s, nil
	case "load":
		raw, bits, err := l.loadRaw(e)
		if err != nil {
			return ssaVal{}, err
		}
		if bits == 64 {
			return ssaVal{raw, "i64"}, nil
		}
		v := l.val()
		ext := "arith.extui"
		if e.Map.Signed {
			ext = "arith.extsi"
		}
		l.emit("%s = %s %s : i32 to i64 %s", v, ext, raw, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "ringout":
		return l.ringOutput(e.Ring, e.Args[0], e.Pos, true)
	case "hstatus":
		return l.hashStatus(e)
	case "ktime":
		v := l.val()
		l.emit("%s = ebpf.ktime.ns : i64 %s", v, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "gload":
		v := l.val()
		l.emit("%s = ebpf.global.load @%s : i%d %s", v, e.Glob.Name, e.Glob.Bits, loc(e.Pos))
		if e.Glob.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Glob.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Glob.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "call":
		var as, tys []string
		for _, a := range e.Args {
			if a.Kind == "winarg" {
				wb, ok := l.wins[a.Ref]
				if !ok {
					return ssaVal{}, fmt.Errorf("internal: window %s outside its in_range region at %s", a.Ref, a.Pos)
				}
				as = append(as, wb.name)
				tys = append(tys, fmt.Sprintf("!ebpf.pkt_window<%d>", a.Len))
				continue
			}
			if a.Kind == "ctxarg" {
				as = append(as, "%ctx")
				tys = append(tys, fmt.Sprintf("!ebpf.ctx<%q>", a.Var))
				continue
			}
			if a.Kind == "refarg" {
				br, ok := l.refs[a.Ref]
				if !ok {
					return ssaVal{}, fmt.Errorf("internal: borrowed %s outside its present region at %s", a.Ref, a.Pos)
				}
				as = append(as, br.name)
				tys = append(tys, fmt.Sprintf("!ebpf.borrowed<%s>", valueType(a.Map)))
				continue
			}
			x, err := l.expr(a)
			if err != nil {
				return ssaVal{}, err
			}
			as = append(as, x.name)
			tys = append(tys, "i64")
		}
		v := l.val()
		l.emit("%s = ebpf.call @%s(%s) : (%s) -> i64 %s", v, e.Var, strings.Join(as, ", "), strings.Join(tys, ", "), loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "pidtgid":
		v := l.val()
		l.emit("%s = ebpf.task.pid_tgid : i64 %s", v, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "kaddr":
		v := l.val()
		if mutation("kaddr-zero") {
			l.emit("%s = arith.constant 0 : i64 %s", v, loc(e.Pos))
			return ssaVal{v, "i64"}, nil
		}
		l.emit("%s = ebpf.kptr.addr %s : !ebpf.kptr<%q> -> i64 %s", v, l.env[e.Var].name, e.Path, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "kfload":
		v := l.val()
		fname := e.Field.Name
		if fname == "__sk_common.skc_daddr" && mutation("kpath-leaf-swap") {
			fname = "__sk_common.skc_rcv_saddr"
		}
		l.emit("%s = ebpf.kfield.load %s %q : !ebpf.kptr<%q> -> i%d %s", v, l.env[e.Var].name, fname, e.Path, e.Field.Bits, loc(e.Pos))
		if e.Field.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "tpfield":
		v := l.val()
		l.emit("%s = ebpf.tp.field %%ctx %q [%d] : !ebpf.ctx<%q> -> i%d %s", v, e.Field.Name, e.Idx, l.kind, e.Field.Bits, loc(e.Pos))
		if e.Field.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "rawarg":
		i := e.Idx
		if mutation("rawtp-index") && i < 2 {
			i ^= 1
		}
		v := l.val()
		l.emit("%s = ebpf.ctx.field %%ctx \"args\"[%d] : !ebpf.ctx<%q> -> i64 %s", v, i, l.kind, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "kretval":
		v := l.val()
		l.emit("%s = ebpf.probe.retval %%ctx : !ebpf.ctx<%q> -> i%d %s", v, l.kind, e.Field.Bits, loc(e.Pos))
		if e.Field.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed && !mutation("kretval-zext") {
			ext = "arith.extsi"
		}
		if !e.Field.Signed && l.kind == "uretprobe" && mutation("uretval-sext") {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "fkload":
		v := l.val()
		idx := ""
		if e.Idx >= 0 {
			idx = fmt.Sprintf("[%d]", e.Idx)
		}
		l.emit("%s = ebpf.flow_keys.load %%ctx %q%s : !ebpf.ctx<\"flow_dissector\"> -> i%d %s", v, e.Field.Name, idx, e.Field.Bits, loc(e.Pos))
		x := l.val()
		l.emit("%s = arith.extui %s : i%d to i64 %s", x, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "adjt":
		k := e.Idx
		if mutation("adjt-zero") {
			k = 0
		}
		c := l.val()
		l.emit("%s = arith.constant %d : i32 %s", c, k, loc(e.Pos))
		v := l.val()
		l.emit("%s = ebpf.xdp.adjust_tail %%ctx, %s : !ebpf.ctx<\"xdp\"> -> i64 %s", v, c, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "adjh":
		d, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		if mutation("adjh-neg") {
			z := l.val()
			l.emit("%s = arith.constant 0 : i64 %s", z, loc(e.Pos))
			n := l.val()
			l.emit("%s = arith.subi %s, %s : i64 %s", n, z, d.name, loc(e.Pos))
			d = ssaVal{n, "i64"}
		}
		t := l.val()
		l.emit("%s = arith.trunci %s : i64 to i32 %s", t, d.name, loc(e.Pos))
		v := l.val()
		l.emit("%s = ebpf.xdp.adjust_head %%ctx, %s : !ebpf.ctx<\"xdp\"> -> i64 %s", v, t, loc(e.Pos))
		return ssaVal{v, "i64"}, nil
	case "ctxfield":
		v := l.val()
		l.emit("%s = ebpf.ctx.field %%ctx %q : !ebpf.ctx<%q> -> i%d %s", v, e.Field.Name, l.kind, e.Field.Bits, loc(e.Pos))
		x := l.val()
		l.emit("%s = arith.extui %s : i%d to i64 %s", x, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "retval", "kparg":
		v := l.val()
		if e.Kind == "retval" {
			l.emit("%s = ebpf.ctx.retval %%ctx after %d : !ebpf.ctx<\"fexit\"> -> i%d %s", v, e.Idx, e.Field.Bits, loc(e.Pos))
		} else if l.kind == "tp_btf" || l.kind == "fentry" || l.kind == "fmod_ret" {
			i := e.Idx
			if l.kind == "fentry" && mutation("fentry-arg-swap") && (i == 0 || i == 5) {
				i = 5 - i
			}
			l.emit("%s = ebpf.ctx.arg %%ctx[%d] : !ebpf.ctx<%q> -> i%d %s", v, i, l.kind, e.Field.Bits, loc(e.Pos))
		} else if l.kind == "ksyscall" {
			n := e.Idx
			if mutation("ksyscall-swap34") && (n == 3 || n == 4) {
				n = 7 - n
			}
			l.emit("%s = ebpf.ksyscall.arg %%ctx %d : !ebpf.ctx<\"ksyscall\"> -> i%d %s", v, n, e.Field.Bits, loc(e.Pos))
		} else if l.kind == "uprobe" {
			l.emit("%s = ebpf.uprobe.arg %%ctx %d : !ebpf.ctx<\"uprobe\"> -> i%d %s", v, e.Idx, e.Field.Bits, loc(e.Pos))
			if e.Field.Name == "ptr" && mutation("uprobe-ptr-trunc") {
				t, w := l.val(), l.val()
				l.emit("%s = arith.trunci %s : i64 to i32 %s", t, v, loc(e.Pos))
				l.emit("%s = arith.extsi %s : i32 to i64 %s", w, t, loc(e.Pos))
				return ssaVal{w, "i64"}, nil
			}
		} else {
			n := e.Idx
			if e.Field.Name == "ptr" && mutation("kprobe-ptr-swap") && (n == 2 || n == 3) {
				n = 5 - n
			}
			l.emit("%s = ebpf.kprobe.arg %%ctx %d : !ebpf.ctx<\"kprobe\"> -> i%d %s", v, n, e.Field.Bits, loc(e.Pos))
		}
		if e.Field.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "fload":
		br, ok := l.refs[e.Ref]
		if !ok {
			return ssaVal{}, fmt.Errorf("internal: %s.load.%s outside the present region at %s", e.Ref, e.Field.Name, e.Pos)
		}
		v := l.val()
		path := e.Field.Name
		if e.Path != "" {
			path = e.Path
		}
		l.emit("%s = ebpf.ref.field.load %s %q : !ebpf.borrowed<%s> -> i%d %s", v, br.name, path, e.Map.Record.MLIRType(), e.Field.Bits, loc(e.Pos))
		if e.Field.Bits == 64 {
			return ssaVal{v, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : i%d to i64 %s", x, ext, v, e.Field.Bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "iload":
		br, ok := l.refs[e.Ref]
		if !ok {
			return ssaVal{}, fmt.Errorf("internal: %s.load.%s[…] outside the present region at %s", e.Ref, e.Field.Name, e.Pos)
		}
		ix, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		t := l.index32(ix.name, e.Pos)
		r, el, v, z := l.val(), l.val(), l.val(), l.val()
		w := fmt.Sprintf("i%d", e.Field.Bits)
		l.emit("%s = ebpf.ref.index %s %q [%s] : !ebpf.borrowed<%s>, i32 -> %s in_range {", r, br.name, e.Field.Name, t, e.Map.Record.MLIRType(), w)
		l.emit("^bb0(%s: !ebpf.elem<%s>):", el, w)
		l.emit("  %s = ebpf.elem.load %s : !ebpf.elem<%s> -> %s %s", v, el, w, w, loc(e.Pos))
		l.emit("  ebpf.yield %s : %s %s", v, w, loc(e.Pos))
		l.emit("} out_of_range {")
		l.emit("  // unreachable — the index range is [0, %d] (proved by the frontend)", e.Field.Count-1)
		l.emit("  %s = arith.constant 0 : %s %s", z, w, loc(e.Pos))
		l.emit("  ebpf.yield %s : %s %s", z, w, loc(e.Pos))
		l.emit("} %s", loc(e.Pos))
		if e.Field.Bits == 64 {
			return ssaVal{r, "i64"}, nil
		}
		ext := "arith.extui"
		if e.Field.Signed {
			ext = "arith.extsi"
		}
		x := l.val()
		l.emit("%s = %s %s : %s to i64 %s", x, ext, r, w, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "wload":
		w, ok := l.wins[e.Ref]
		if !ok {
			return ssaVal{}, fmt.Errorf("internal: %s.%s outside the in-range region at %s", e.Ref, e.Op, e.Pos)
		}
		bits := windowReads[e.Op] * 8
		v := l.val()
		l.emit("%s = ebpf.packet.window_load %s[%d] : !ebpf.pkt_window<%d> -> i%d %s", v, w.name, e.Idx, w.bits, bits, loc(e.Pos))
		if bits > 8 && e.Op[:2] == "be" {
			b := l.val()
			l.emit("%s = ebpf.byteorder.from_be %s : i%d %s", b, v, bits, loc(e.Pos))
			v = b
		}
		x := l.val()
		l.emit("%s = arith.extui %s : i%d to i64 %s", x, v, bits, loc(e.Pos))
		return ssaVal{x, "i64"}, nil
	case "un":
		x, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		c, v := l.val(), l.val()
		if e.Op == "-@" {
			l.emit("%s = arith.constant 0 : i64 %s", c, loc(e.Pos))
			l.emit("%s = arith.subi %s, %s : i64 %s", v, c, x.name, loc(e.Pos))
		} else {
			l.emit("%s = arith.constant -1 : i64 %s", c, loc(e.Pos))
			l.emit("%s = arith.xori %s, %s : i64 %s", v, x.name, c, loc(e.Pos))
		}
		return ssaVal{v, "i64"}, nil
	case "bin":
		return l.binary(e)
	case "cmp":
		a, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		b, err := l.expr(e.Args[1])
		if err != nil {
			return ssaVal{}, err
		}
		pred := map[string]string{"==": "eq", "!=": "ne", "<": "slt", "<=": "sle", ">": "sgt", ">=": "sge"}[e.Op]
		if mutation("swap-operands") {
			a, b = b, a
		}
		if pred == "sgt" && l.kind == "socket_filter" && mutation("sf-ge") {
			pred = "sge"
		}
		v := l.val()
		l.emit("%s = arith.cmpi %s, %s, %s : i64 %s", v, pred, a.name, b.name, loc(e.Pos))
		return ssaVal{v, "i1"}, nil
	case "and", "or":
		a, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		b, err := l.expr(e.Args[1])
		if err != nil {
			return ssaVal{}, err
		}
		op := map[string]string{"and": "arith.andi", "or": "arith.ori"}[e.Kind]
		v := l.val()
		l.emit("%s = %s %s, %s : i1 %s", v, op, a.name, b.name, loc(e.Pos))
		return ssaVal{v, "i1"}, nil
	case "not":
		a, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		t, v := l.val(), l.val()
		l.emit("%s = arith.constant true %s", t, loc(e.Pos))
		l.emit("%s = arith.xori %s, %s : i1 %s", v, a.name, t, loc(e.Pos))
		return ssaVal{v, "i1"}, nil
	case "sel":
		c, err := l.expr(e.Args[0])
		if err != nil {
			return ssaVal{}, err
		}
		a, err := l.expr(e.Args[1])
		if err != nil {
			return ssaVal{}, err
		}
		b, err := l.expr(e.Args[2])
		if err != nil {
			return ssaVal{}, err
		}
		v := l.val()
		l.emit("%s = arith.select %s, %s, %s : %s %s", v, c.name, a.name, b.name, a.ty, loc(e.Pos))
		return ssaVal{v, a.ty}, nil
	}
	return ssaVal{}, fmt.Errorf("internal: expression kind %q", e.Kind)
}

func (l *lowerer) loadRaw(e *Expr) (string, int, error) {
	br, ok := l.refs[e.Ref]
	if !ok {
		return "", 0, fmt.Errorf("internal: p.load outside the present region at %s", e.Pos)
	}
	v := l.val()
	l.emit("%s = ebpf.ref.load %s : !ebpf.borrowed<i%d> -> i%d %s", v, br.name, br.bits, br.bits, loc(e.Pos))
	return v, br.bits, nil
}

func (l *lowerer) binary(e *Expr) (ssaVal, error) {
	a, err := l.expr(e.Args[0])
	if err != nil {
		return ssaVal{}, err
	}
	b, err := l.expr(e.Args[1])
	if err != nil {
		return ssaVal{}, err
	}
	if mutation("swap-operands") && e.Op == "-" {
		a, b = b, a
	}
	at := loc(e.Pos)
	op := map[string]string{"+": "arith.addi", "-": "arith.subi", "*": "arith.muli", "&": "arith.andi", "|": "arith.ori", "^": "arith.xori", "<<": "arith.shli", ">>": "arith.shrsi"}[e.Op]
	if e.Op == ">>" && e.Args[0].Wide {
		op = "arith.shrui"
	}
	switch e.Op {
	case "/":
		op = map[string]string{"u": "arith.divui", "floor": "arith.floordivsi"}[e.Div]
	case "%":
		if e.Div == "u" {
			op = "arith.remui"
			break
		}
		d := e.Args[1].Lit
		r, z, rnz, rbad, fix, rd, m := l.val(), l.val(), l.val(), l.val(), l.val(), l.val(), l.val()
		l.emit("%s = arith.remsi %s, %s : i64 %s", r, a.name, b.name, at)
		l.emit("%s = arith.constant 0 : i64 %s", z, at)
		l.emit("%s = arith.cmpi ne, %s, %s : i64 %s", rnz, r, z, at)
		pred := "slt"
		if d.Sign() < 0 {
			pred = "sgt"
		}
		l.emit("%s = arith.cmpi %s, %s, %s : i64 %s", rbad, pred, r, z, at)
		l.emit("%s = arith.andi %s, %s : i1 %s", fix, rnz, rbad, at)
		l.emit("%s = arith.addi %s, %s : i64 %s", rd, r, b.name, at)
		l.emit("%s = arith.select %s, %s, %s : i64 %s", m, fix, rd, r, at)
		return ssaVal{m, "i64"}, nil
	}
	if op == "" {
		return ssaVal{}, fmt.Errorf("internal: operator %q", e.Op)
	}
	v := l.val()
	l.emit("%s = %s %s, %s : i64 %s", v, op, a.name, b.name, at)
	return ssaVal{v, "i64"}, nil
}

func (l *lowerer) mapKey(e *Expr, m *MapDecl) (string, error) {
	switch {
	case m.IsArray() || (m.KeyRecord == nil && m.KeyBits == 32):
		return l.keyOperand(e)
	case m.KeyRecord != nil:
		return l.valueOperand(e, e.Map)
	case e.Kind == "lit":
		v := l.val()
		l.emit("%s = arith.constant %s : i64 %s", v, e.Lit, loc(e.Pos))
		return v, nil
	}
	x, err := l.expr(e)
	return x.name, err
}

func (l *lowerer) keyOperand(e *Expr) (string, error) {
	if e.Kind == "lit" {
		v := l.val()
		l.emit("%s = arith.constant %s : i32 %s", v, i32Text(e.Lit.Int64()), loc(e.Pos))
		return v, nil
	}
	x, err := l.expr(e)
	if err != nil {
		return "", err
	}
	v := l.val()
	l.emit("%s = arith.trunci %s : i64 to i32 %s", v, x.name, loc(e.Pos))
	return v, nil
}

func (l *lowerer) valueOperand(e *Expr, m *MapDecl) (string, error) {
	if e.Kind == "rmake" {
		var names, vals, tys []string
		for i, f := range m.Record.Fields {
			if f.Pad {
				continue
			}
			if e.Args[i].Kind == "zarr" {
				z := l.val()
				l.emit("%s = arith.constant 0 : i%d %s", z, f.Bits, loc(e.Args[i].Pos))
				for k := 0; k < f.Count; k++ {
					names = append(names, fmt.Sprintf("%q", fmt.Sprintf("%s[%d]", f.Name, k)))
					vals = append(vals, z)
					tys = append(tys, fmt.Sprintf("i%d", f.Bits))
				}
				continue
			}
			if e.Args[i].Kind == "earr" {
				el := RecordField{Name: f.Name, Bits: f.Bits, Signed: f.Signed}
				for k, x := range e.Args[i].Args {
					v, err := l.fieldOperand(x, &el)
					if err != nil {
						return "", err
					}
					names = append(names, fmt.Sprintf("%q", fmt.Sprintf("%s[%d]", f.Name, k)))
					vals = append(vals, v)
					tys = append(tys, fmt.Sprintf("i%d", f.Bits))
				}
				continue
			}
			v, err := l.fieldOperand(e.Args[i], &m.Record.Fields[i])
			if err != nil {
				return "", err
			}
			names = append(names, fmt.Sprintf("%q", f.Name))
			vals = append(vals, v)
			tys = append(tys, fmt.Sprintf("i%d", f.Bits))
		}
		r := l.val()
		l.emit("%s = ebpf.record.make [%s] (%s) : (%s) -> %s %s", r, strings.Join(names, ", "), strings.Join(vals, ", "), strings.Join(tys, ", "), m.Record.MLIRType(), loc(e.Pos))
		return r, nil
	}
	if e.Kind == "lit" {
		v := l.val()
		lit := e.Lit.Int64()
		txt := fmt.Sprint(lit)
		if m.ValueBits == 32 {
			txt = i32Text(lit)
		}
		l.emit("%s = arith.constant %s : i%d %s", v, txt, m.ValueBits, loc(e.Pos))
		return v, nil
	}
	if e.Kind == "load" && e.Map.ValueBits == m.ValueBits {
		raw, _, err := l.loadRaw(e)
		return raw, err
	}
	x, err := l.expr(e)
	if err != nil {
		return "", err
	}
	if m.ValueBits == 64 {
		return x.name, nil
	}
	v := l.val()
	l.emit("%s = arith.trunci %s : i64 to i32 %s", v, x.name, loc(e.Pos))
	return v, nil
}

func (l *lowerer) ringOutput(r *RingDecl, mk *Expr, pos Pos, withResult bool) (ssaVal, error) {
	rec := r.Record.MLIRType()
	rv := l.val()
	l.emit("%s = ebpf.ringbuf.reserve %q : !ebpf.maybe_reservation<%s> %s", rv, r.Name, rec, loc(pos))
	ok := ""
	if withResult {
		ok = l.val()
	}
	res := l.val()
	var b strings.Builder
	saved, savedIndent := l.b, l.indent
	l.b, l.indent = &b, l.indent+"  "
	if mutation("ring-swap") && len(mk.Args) >= 2 {
		c := *mk
		c.Args = append([]*Expr{mk.Args[1], mk.Args[0]}, mk.Args[2:]...)
		mk = &c
	}
	v, err := l.valueOperand(mk, &MapDecl{Name: r.Name, Record: r.Record})
	if err != nil {
		l.b, l.indent = saved, savedIndent
		return ssaVal{}, err
	}
	l.emit("ebpf.ringbuf.store_record %s, %s : !ebpf.reservation<%s>, %s %s", res, v, rec, rec, loc(pos))
	for _, a := range mk.Args {
		if a.Kind == "zarr" && a.Var != "" && !mutation("kcopy-ring-drop") {
			l.emit("ebpf.kfield.copy %s %q, %s %q : !ebpf.kptr<%q>, !ebpf.reservation<%s> %s", l.env[a.Var].name, a.Path, res, a.Field.Name, a.Op, rec, loc(a.Pos))
		}
		if a.Kind == "zarr" && a.TpCopy != nil && !mutation("tp-copy-drop") {
			l.emit("ebpf.tp.field.copy %s %q, %%ctx %q [%d] : !ebpf.reservation<%s>, !ebpf.ctx<\"tracepoint\"> %s", res, a.Field.Name, a.TpCopy.Name, tpCopyOffset(a.TpCopy), rec, loc(a.Pos))
		}
	}
	l.emit("ebpf.ringbuf.submit %s : !ebpf.reservation<%s> %s", res, rec, loc(pos))
	yes, no := "true", "false"
	if mutation("ring-invert") {
		yes, no = no, yes
	}
	if withResult {
		t := l.val()
		l.emit("%s = arith.constant %s %s", t, yes, loc(pos))
		l.emit("ebpf.yield %s : i1 %s", t, loc(pos))
	} else {
		l.emit("ebpf.yield %s", loc(pos))
	}
	present := b.String()
	var ab strings.Builder
	l.b = &ab
	if withResult {
		f := l.val()
		l.emit("%s = arith.constant %s %s", f, no, loc(pos))
		l.emit("ebpf.yield %s : i1 %s", f, loc(pos))
	} else {
		l.emit("ebpf.yield %s", loc(pos))
	}
	absent := ab.String()
	l.b, l.indent = saved, savedIndent
	decl, head := "", ""
	if withResult {
		decl, head = " -> i1", ok+" = "
	}
	l.emit("%sebpf.ringbuf.if_reserved %s : !ebpf.maybe_reservation<%s>%s present {", head, rv, rec, decl)
	l.emit("^present(%s: !ebpf.reservation<%s>):", res, rec)
	l.b.WriteString(present)
	l.emit("} absent {")
	l.b.WriteString(absent)
	l.emit("} %s", loc(pos))
	return ssaVal{ok, "i1"}, nil
}

func (l *lowerer) fieldOperand(e *Expr, f *RecordField) (string, error) {
	if e.Kind == "lit" {
		v := l.val()
		lit := e.Lit.Int64()
		if !f.Signed && f.Bits < 64 && lit >= 1<<(f.Bits-1) {
			lit -= 1 << f.Bits
		}
		l.emit("%s = arith.constant %d : i%d %s", v, lit, f.Bits, loc(e.Pos))
		return v, nil
	}
	if e.Kind == "fload" && e.Field.Bits == f.Bits {
		br := l.refs[e.Ref]
		v := l.val()
		l.emit("%s = ebpf.ref.field.load %s %q : !ebpf.borrowed<%s> -> i%d %s", v, br.name, e.Field.Name, e.Map.Record.MLIRType(), e.Field.Bits, loc(e.Pos))
		return v, nil
	}
	if e.Kind == "load" && e.Map.ValueBits == f.Bits {
		raw, _, err := l.loadRaw(e)
		return raw, err
	}
	x, err := l.expr(e)
	if err != nil {
		return "", err
	}
	if f.Bits == 64 {
		return x.name, nil
	}
	v := l.val()
	l.emit("%s = arith.trunci %s : i64 to i%d %s", v, x.name, f.Bits, loc(e.Pos))
	return v, nil
}

func i32Text(v int64) string {
	if v >= 1<<31 {
		v = int64(int32(uint32(v)))
	}
	return fmt.Sprint(v)
}

func (l *lowerer) copyEnv() map[string]ssaVal {
	out := map[string]ssaVal{}
	for k, v := range l.env {
		out[k] = v
	}
	return out
}

func (l *lowerer) arm(ss []Stmt, pre map[string]ssaVal, indent string) (string, map[string]ssaVal, error) {
	var b strings.Builder
	saved, savedIndent := l.b, l.indent
	l.b, l.indent, l.env = &b, indent, copyMap(pre)
	err := l.stmts(ss)
	env := l.env
	l.b, l.indent = saved, savedIndent
	return b.String(), env, err
}

func copyMap(m map[string]ssaVal) map[string]ssaVal {
	out := map[string]ssaVal{}
	for k, v := range m {
		out[k] = v
	}
	return out
}

func results(pre, a, b map[string]ssaVal) []string {
	var out []string
	for k, va := range a {
		vb, ok := b[k]
		if !ok {
			continue
		}
		if p, had := pre[k]; had && p == va && p == vb {
			continue
		}
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func regionTypes(vars []string, env map[string]ssaVal) (string, []string) {
	var tys []string
	for _, k := range vars {
		tys = append(tys, env[k].ty)
	}
	switch len(tys) {
	case 0:
		return "", nil
	case 1:
		return " -> " + tys[0], tys
	}
	return " -> " + strings.Join(tys, ", "), tys
}

func yieldText(op string, vars []string, env map[string]ssaVal, tys []string) string {
	if len(vars) == 0 {
		return op
	}
	var names []string
	for _, k := range vars {
		names = append(names, env[k].name)
	}
	return fmt.Sprintf("%s %s : %s", op, strings.Join(names, ", "), strings.Join(tys, ", "))
}

func (l *lowerer) bindResults(res string, vars []string, tys []string) {
	for i, k := range vars {
		name := res
		if len(vars) > 1 {
			name = fmt.Sprintf("%s#%d", res, i)
		}
		l.env[k] = ssaVal{name, tys[i]}
	}
}

func resultDecl(res string, n int) string {
	switch n {
	case 0:
		return ""
	case 1:
		return res + " = "
	}
	return fmt.Sprintf("%s:%d = ", res, n)
}

func (l *lowerer) stmts(ss []Stmt) error {
	for _, s := range ss {
		switch s.Kind {
		case "assign":
			x, err := l.expr(s.Val)
			if err != nil {
				return err
			}
			l.env[s.Var] = x
		case "skassign":
			if err := l.skAssign(s); err != nil {
				return err
			}
		case "kread":
			a := l.val()
			l.emit("%s = ebpf.kprobe.arg %%ctx %d : !ebpf.ctx<\"kprobe\"> -> i64 %s", a, s.Count, loc(s.Pos))
			off := s.Len
			if mutation("kread-offset") && off >= 8 {
				off -= 8
			}
			r := l.val()
			l.emit("%s:2 = ebpf.kernel.read_scalar %s offset %d : i64 -> i%d, i64 %s", r, a, off, s.Field.Bits, loc(s.Pos))
			v := ssaVal{r + "#0", "i64"}
			if s.Field.Bits < 64 {
				ext := "arith.extui"
				if s.Field.Signed {
					ext = "arith.extsi"
				}
				x := l.val()
				l.emit("%s = %s %s#0 : i%d to i64 %s", x, ext, r, s.Field.Bits, loc(s.Pos))
				v = ssaVal{x, "i64"}
			}
			if s.Var != "_" {
				l.env[s.Var] = v
			}
			l.env[s.Path] = ssaVal{r + "#1", "i64"}
		case "fkstore":
			v, err := l.expr(s.Val)
			if err != nil {
				return err
			}
			field := s.Path
			if field == "ipv4_src" && mutation("flow-swap-addr") {
				field = "ipv4_dst"
			}
			bits := flowFields[field].Bits
			t := l.val()
			l.emit("%s = arith.trunci %s : i64 to i%d %s", t, v.name, bits, loc(s.Pos))
			idx := ""
			if s.Count >= 0 {
				idx = fmt.Sprintf("[%d]", s.Count)
			}
			l.emit("ebpf.flow_keys.store %%ctx %q%s, %s : !ebpf.ctx<\"flow_dissector\">, i%d %s", field, idx, t, bits, loc(s.Pos))
		case "ctxstore":
			if mutation("no-mark-store") {
				continue
			}
			v, err := l.expr(s.Val)
			if err != nil {
				return err
			}
			t := l.val()
			l.emit("%s = arith.trunci %s : i64 to i32 %s", t, v.name, loc(s.Pos))
			l.emit("ebpf.ctx.field.store %%ctx %q, %s : !ebpf.ctx<%q>, i32 %s", s.Path, t, l.kind, loc(s.Pos))
		case "kptr":
			v := l.val()
			if l.kind == "netfilter" {
				l.emit("%s = ebpf.ctx.field %%ctx %q : !ebpf.ctx<\"netfilter\"> -> !ebpf.kptr<%q> %s", v, s.Path, s.KT.Name, loc(s.Pos))
			} else {
				l.emit("%s = ebpf.ctx.arg %%ctx[%d] : !ebpf.ctx<\"tp_btf\"> -> !ebpf.kptr<%q> %s", v, s.Len, s.KT.Name, loc(s.Pos))
			}
			l.env[s.Var] = ssaVal{v, "kptr"}
		case "kcheck":
			r := l.val()
			if s.PtrOf == "" {
				l.emit("%s = ebpf.ctx.arg %%ctx[%d] : !ebpf.ctx<%q> -> !ebpf.kptr_or_null<%q> %s", r, s.Len, l.kind, s.KT.Name, loc(s.Pos))
			} else {
				l.emit("%s = ebpf.kfield.ptr %s %q : !ebpf.kptr<%q> -> !ebpf.kptr_or_null<%q> %s", r, l.env[s.PtrOf].name, s.Path, s.PtrOfKT.Name, s.KT.Name, loc(s.Pos))
			}
			pre := l.copyEnv()
			q := l.val()
			pin := copyMap(pre)
			pin[s.Var] = ssaVal{q, "kptr"}
			thenText, thenEnv, err := l.arm(s.Then, pin, l.indent+"  ")
			if err != nil {
				return err
			}
			delete(thenEnv, s.Var)
			elseText, elseEnv, err := l.arm(s.Else, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			l.env = pre
			escT, escE := escapes(s.Then), escapes(s.Else)
			vars, tyEnv := armResults(pre, thenEnv, elseEnv, escT, escE)
			decl, tys := regionTypes(vars, tyEnv)
			res := ""
			if len(vars) > 0 {
				res = l.val()
			}
			l.emit("%sebpf.kptr.check %s : !ebpf.kptr_or_null<%q>%s present {", resultDecl(res, len(vars)), r, s.KT.Name, decl)
			l.emit("^present(%s: !ebpf.kptr<%q>):", q, s.KT.Name)
			l.b.WriteString(thenText)
			if !escT {
				l.emit("  %s %s", yieldText("ebpf.yield", vars, thenEnv, tys), loc(s.IfPos))
			}
			l.emit("} absent {")
			l.b.WriteString(elseText)
			if !escE {
				l.emit("  %s %s", yieldText("ebpf.yield", vars, elseEnv, tys), loc(s.IfPos))
			}
			l.emit("} %s", loc(s.Pos))
			l.bindResults(res, vars, tys)
		case "kcopy":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			l.emit("ebpf.kfield.copy %s %q, %s %q : !ebpf.kptr<%q>, !ebpf.borrowed<%s> %s", l.env[s.PtrOf].name, s.Path, br.name, s.Field.Name, s.PtrOfKT.Name, s.Map.Record.MLIRType(), loc(s.Pos))
		case "tpcopy":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			l.emit("ebpf.tp.field.copy %s %q, %%ctx %q [%d] : !ebpf.borrowed<%s>, !ebpf.ctx<\"tracepoint\"> %s", br.name, s.Field.Name, s.TpCopy.Name, tpCopyOffset(s.TpCopy), s.Map.Record.MLIRType(), loc(s.Pos))
		case "ostr":
			if err := l.outputStr(s); err != nil {
				return err
			}
		case "guard":
			c, err := l.expr(s.Cond)
			if err != nil {
				return err
			}
			pre := l.copyEnv()
			var b strings.Builder
			saved, savedIndent, savedFired := l.b, l.indent, l.fired
			l.b, l.indent, l.env, l.fired = &b, l.indent+"  ", copyMap(pre), ""
			err = l.stmts(s.Else)
			inner := l.fired
			if inner == "" {
				inner = l.val()
				l.emit("%s = arith.constant false %s", inner, loc(s.Pos))
			}
			l.b, l.indent, l.fired = saved, savedIndent, savedFired
			if err != nil {
				return err
			}
			l.env = pre
			f, t := l.val(), l.val()
			l.emit("%s = ebpf.if %s -> i1 {", f, c.name)
			l.emit("  %s = arith.constant true %s", t, loc(s.Pos))
			l.emit("  ebpf.if.yield %s : i1 %s", t, loc(s.Pos))
			l.emit("} else {")
			l.b.WriteString(b.String())
			l.emit("  ebpf.if.yield %s : i1 %s", inner, loc(s.Pos))
			l.emit("} %s", loc(s.Pos))
			l.fired = f
		case "loop":
			if err := l.loop(s); err != nil {
				return err
			}
		case "break", "next":
			op := map[string]string{"break": "ebpf.break", "next": "ebpf.continue"}[s.Kind]
			carried := l.loops[len(l.loops)-1]
			_, tys := regionTypes(carried, l.env)
			l.emit("%s %s", yieldText(op, carried, l.env, tys), loc(s.Pos))
		case "gadd":
			x, err := l.expr(s.Val)
			if err != nil {
				return err
			}
			d := x.name
			if s.Glob.Bits == 32 {
				d = l.val()
				l.emit("%s = arith.trunci %s : i64 to i32 %s", d, x.name, loc(s.Pos))
			}
			l.emit("ebpf.global.atomic_add @%s, %s : i%d %s", s.Glob.Name, d, s.Glob.Bits, loc(s.Pos))
		case "atomic_add", "update":
			m := l.maps[s.Map]
			k, err := l.keyOperand(s.Key)
			if err != nil {
				return err
			}
			v, err := l.valueOperand(s.Value, s.Map)
			if err != nil {
				return err
			}
			l.emit("ebpf.map.%s %s[%s], %s : %s, i32, %s %s", s.Kind, m, k, v, mapType(s.Map), valueType(s.Map), loc(s.Pos))
		case "if":
			c, err := l.expr(s.Cond)
			if err != nil {
				return err
			}
			pre := l.copyEnv()
			thenText, thenEnv, err := l.arm(s.Then, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			elseText, elseEnv, err := l.arm(s.Else, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			l.env = pre
			escT, escE := escapes(s.Then), escapes(s.Else)
			vars, tyEnv := armResults(pre, thenEnv, elseEnv, escT, escE)
			decl, tys := regionTypes(vars, tyEnv)
			res := ""
			if len(vars) > 0 {
				res = l.val()
			}
			l.emit("%sebpf.if %s%s {", resultDecl(res, len(vars)), c.name, decl)
			l.b.WriteString(thenText)
			if !escT {
				l.emit("  %s %s", yieldText("ebpf.if.yield", vars, thenEnv, tys), loc(s.Pos))
			}
			l.emit("} else {")
			l.b.WriteString(elseText)
			if !escE {
				l.emit("  %s %s", yieldText("ebpf.if.yield", vars, elseEnv, tys), loc(s.Pos))
			}
			l.emit("} %s", loc(s.Pos))
			l.bindResults(res, vars, tys)
		case "lookup_check":
			m := l.maps[s.Map]
			vb, vt := s.Map.ValueBits, valueType(s.Map)
			k, err := l.mapKey(s.Key, s.Map)
			if err != nil {
				return err
			}
			r := l.val()
			l.emit("%s = ebpf.map.lookup %s[%s] : %s, %s -> !ebpf.maybe_ref<%s> %s", r, m, k, mapType(s.Map), keyType(s.Map), vt, loc(s.Pos))
			pre := l.copyEnv()
			bor := l.val()
			l.refs[s.Var] = borrow{bor, vb}
			thenText, thenEnv, err := l.arm(s.Then, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			elseText, elseEnv, err := l.arm(s.Else, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			delete(l.refs, s.Var)
			l.env = pre
			escT, escE := escapes(s.Then), escapes(s.Else)
			vars, tyEnv := armResults(pre, thenEnv, elseEnv, escT, escE)
			decl, tys := regionTypes(vars, tyEnv)
			res := ""
			if len(vars) > 0 {
				res = l.val()
			}
			l.emit("%sebpf.ref.check %s : !ebpf.maybe_ref<%s>%s present {", resultDecl(res, len(vars)), r, vt, decl)
			l.emit("^present(%s: !ebpf.borrowed<%s>):", bor, vt)
			l.b.WriteString(thenText)
			if !escT {
				l.emit("  %s %s", yieldText("ebpf.yield", vars, thenEnv, tys), loc(s.IfPos))
			}
			l.emit("} absent {")
			l.b.WriteString(elseText)
			if !escE {
				l.emit("  %s %s", yieldText("ebpf.yield", vars, elseEnv, tys), loc(s.IfPos))
			}
			l.emit("} %s", loc(s.Pos))
			l.bindResults(res, vars, tys)
		case "fadd":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			rt, bits := s.Map.Record.MLIRType(), s.Field.Bits
			x := l.val()
			l.emit("%s = ebpf.ref.field.load %s %q : !ebpf.borrowed<%s> -> i%d %s", x, br.name, s.Field.Name, rt, bits, loc(s.Pos))
			d, err := l.fieldOperand(s.Value, s.Field)
			if err != nil {
				return err
			}
			y := l.val()
			op := map[string]string{"+": "arith.addi", "-": "arith.subi"}[s.Op]
			if mutation("fadd-sub") {
				op = "arith.subi"
			}
			l.emit("%s = %s %s, %s : i%d %s", y, op, x, d, bits, loc(s.Pos))
			l.emit("ebpf.ref.field.store %s %q, %s : !ebpf.borrowed<%s>, i%d %s", br.name, s.Field.Name, y, rt, bits, loc(s.Pos))
		case "drop":
			if _, err := l.expr(s.Val); err != nil {
				return err
			}
		case "ratomic":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			v, err := l.valueOperand(s.Value, s.Map)
			if err != nil {
				return err
			}
			l.emit("ebpf.ref.atomic_add %s, %s : !ebpf.borrowed<%s>, %s %s", br.name, v, valueType(s.Map), valueType(s.Map), loc(s.Pos))
		case "ringout":
			if _, err := l.ringOutput(s.Ring, s.Value, s.Pos, false); err != nil {
				return err
			}
		case "fstore", "fatomic":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			v, err := l.fieldOperand(s.Value, s.Field)
			if err != nil {
				return err
			}
			op := map[string]string{"fstore": "ebpf.ref.field.store", "fatomic": "ebpf.ref.field.atomic_add"}[s.Kind]
			path := s.Field.Name
			if s.Path != "" {
				path = s.Path
			}
			l.emit("%s %s %q, %s : !ebpf.borrowed<%s>, i%d %s", op, br.name, path, v, s.Map.Record.MLIRType(), s.Field.Bits, loc(s.Pos))
		case "istore":
			br, ok := l.refs[s.Var]
			if !ok {
				return fmt.Errorf("internal: %s outside the present region at %s", s.Var, s.Pos)
			}
			ix, err := l.expr(s.Key)
			if err != nil {
				return err
			}
			v, err := l.fieldOperand(s.Value, s.Field)
			if err != nil {
				return err
			}
			t := l.index32(ix.name, s.Pos)
			el := l.val()
			w := fmt.Sprintf("i%d", s.Field.Bits)
			l.emit("ebpf.ref.index %s %q [%s] : !ebpf.borrowed<%s>, i32 in_range {", br.name, s.Field.Name, t, s.Map.Record.MLIRType())
			l.emit("^bb0(%s: !ebpf.elem<%s>):", el, w)
			l.emit("  ebpf.elem.store %s, %s : !ebpf.elem<%s>, %s %s", el, v, w, w, loc(s.Pos))
			l.emit("  ebpf.yield %s", loc(s.Pos))
			l.emit("} out_of_range {")
			l.emit("  // unreachable — the index range is [0, %d] (proved by the frontend)", s.Field.Count-1)
			l.emit("  ebpf.yield %s", loc(s.Pos))
			l.emit("} %s", loc(s.Pos))
		case "window_check":
			off, err := l.expr(s.Off)
			if err != nil {
				return err
			}
			pre := l.copyEnv()
			w := l.val()
			l.wins[s.Var] = borrow{w, int(s.Len)}
			thenText, thenEnv, err := l.arm(s.Then, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			delete(l.wins, s.Var)
			elseText, elseEnv, err := l.arm(s.Else, pre, l.indent+"  ")
			if err != nil {
				return err
			}
			l.env = pre
			vars := results(pre, thenEnv, elseEnv)
			decl, tys := regionTypes(vars, thenEnv)
			res := ""
			if len(vars) > 0 {
				res = l.val()
			}
			l.emit("%sebpf.packet.check %%ctx[%s] len %d : !ebpf.ctx<%q>, i64%s in_range {", resultDecl(res, len(vars)), off.name, s.Len, l.kind, decl)
			l.emit("^in_range(%s: !ebpf.pkt_window<%d>):", w, s.Len)
			l.b.WriteString(thenText)
			l.emit("  %s %s", yieldText("ebpf.yield", vars, thenEnv, tys), loc(s.IfPos))
			l.emit("} out_of_range {")
			l.b.WriteString(elseText)
			l.emit("  %s %s", yieldText("ebpf.yield", vars, elseEnv, tys), loc(s.IfPos))
			l.emit("} %s", loc(s.Pos))
			l.bindResults(res, vars, tys)
		default:
			return fmt.Errorf("internal: statement kind %q", s.Kind)
		}
	}
	return nil
}

func (l *lowerer) hashStatus(e *Expr) (ssaVal, error) {
	m := e.Map
	mv := l.maps[m]
	k, err := l.mapKey(e.Args[0], m)
	if err != nil {
		return ssaVal{}, err
	}
	at := loc(e.Pos)
	kt, vt := keyType(m), valueType(m)
	if e.Op == "delete" {
		s := l.val()
		l.emit("%s = ebpf.map.try_delete %s[%s] : %s, %s -> i64 %s", s, mv, k, mapType(m), kt, at)
		return ssaVal{s, "i64"}, nil
	}
	v, err := l.valueOperand(e.Args[1], m)
	if err != nil {
		return ssaVal{}, err
	}
	if e.Op != "add_or_init" {
		flag := e.Op
		if mutation("hash-flags") {
			flag = map[string]string{"noexist": "exist", "exist": "noexist", "any": "any"}[flag]
		}
		s := l.val()
		l.emit("%s = ebpf.map.try_update %s[%s], %s flags %q : %s, %s, %s -> i64 %s", s, mv, k, v, flag, mapType(m), kt, vt, at)
		return ssaVal{s, "i64"}, nil
	}
	one := func(ind string) (string, string) {
		r, res, b, z := l.val(), l.val(), l.val(), l.val()
		l.emit("%s%s = ebpf.map.lookup %s[%s] : %s, %s -> !ebpf.maybe_ref<%s> %s", ind, r, mv, k, mapType(m), kt, vt, at)
		l.emit("%s%s = ebpf.ref.check %s : !ebpf.maybe_ref<%s> -> i64 present {", ind, res, r, vt)
		l.emit("%s^present(%s: !ebpf.borrowed<%s>):", ind, b, vt)
		l.emit("%s  ebpf.ref.atomic_add %s, %s : !ebpf.borrowed<%s>, %s %s", ind, b, v, vt, vt, at)
		l.emit("%s  %s = arith.constant 0 : i64 %s", ind, z, at)
		l.emit("%s  ebpf.yield %s : i64 %s", ind, z, at)
		l.emit("%s} absent {", ind)
		return res, r
	}
	res, _ := one("")
	t, ee, c, u := l.val(), l.val(), l.val(), l.val()
	l.emit("  %s = ebpf.map.try_update %s[%s], %s flags \"noexist\" : %s, %s, %s -> i64 %s", t, mv, k, v, mapType(m), kt, vt, at)
	l.emit("  %s = arith.constant -17 : i64 %s", ee, at)
	l.emit("  %s = arith.cmpi eq, %s, %s : i64 %s", c, t, ee, at)
	l.emit("  %s = ebpf.if %s -> i64 {", u, c)
	if mutation("aoi-no-retry-add") {
		z := l.val()
		l.emit("    %s = arith.constant 0 : i64 %s", z, at)
		l.emit("    ebpf.if.yield %s : i64 %s", z, at)
	} else {
		res2, _ := one("    ")
		n2 := l.val()
		l.emit("      %s = arith.constant -2 : i64 %s", n2, at)
		l.emit("      ebpf.yield %s : i64 %s", n2, at)
		l.emit("    } %s", at)
		l.emit("    ebpf.if.yield %s : i64 %s", res2, at)
	}
	l.emit("  } else {")
	l.emit("    ebpf.if.yield %s : i64 %s", t, at)
	l.emit("  } %s", at)
	l.emit("  ebpf.yield %s : i64 %s", u, at)
	l.emit("} %s", at)
	return ssaVal{res, "i64"}, nil
}

func armResults(pre, a, b map[string]ssaVal, escA, escB bool) ([]string, map[string]ssaVal) {
	switch {
	case escA && escB:
		return nil, a
	case escA:
		return results(pre, b, b), b
	case escB:
		return results(pre, a, a), a
	}
	return results(pre, a, b), a
}

func (l *lowerer) loop(s Stmt) error {
	bnd := ""
	if s.Bound != nil {
		x, err := l.expr(s.Bound)
		if err != nil {
			return err
		}
		v := x.name
		if s.Incl {
			one, sum := l.val(), l.val()
			l.emit("%s = arith.constant 1 : i64 %s", one, loc(s.Pos))
			l.emit("%s = arith.addi %s, %s : i64 %s", sum, v, one, loc(s.Pos))
			v = sum
		}
		if s.Clamp {
			z, c, r := l.val(), l.val(), l.val()
			l.emit("%s = arith.constant 0 : i64 %s", z, loc(s.Pos))
			l.emit("%s = arith.cmpi slt, %s, %s : i64 %s", c, v, z, loc(s.Pos))
			l.emit("%s = ebpf.if %s -> i64 {", r, c)
			l.emit("  ebpf.if.yield %s : i64 %s", z, loc(s.Pos))
			l.emit("} else {")
			l.emit("  ebpf.if.yield %s : i64 %s", v, loc(s.Pos))
			l.emit("} %s", loc(s.Pos))
			v = r
		}
		t := l.val()
		l.emit("%s = arith.trunci %s : i64 to i32 %s", t, v, loc(s.Pos))
		bnd = " bound(" + t + ")"
	}
	pre := l.copyEnv()
	var inits, tys, params []string
	for _, k := range s.Carried {
		v, ok := pre[k]
		if !ok || v.ty != "i64" {
			return fmt.Errorf("internal: loop value %s is not an i64 local at %s", k, s.Pos)
		}
		inits, tys = append(inits, v.name), append(tys, "i64")
	}
	iv := l.val()
	body := copyMap(pre)
	for _, k := range s.Carried {
		a := l.val()
		params = append(params, a+": i64")
		body[k] = ssaVal{a, "i64"}
	}
	res := ""
	if len(s.Carried) > 0 {
		res = l.val()
	}
	var b strings.Builder
	saved, savedIndent := l.b, l.indent
	l.b, l.indent, l.env = &b, l.indent+"  ", body
	if s.Var != "" {
		x := l.val()
		l.emit("%s = arith.extui %s : i32 to i64 %s", x, iv, loc(s.Pos))
		l.env[s.Var] = ssaVal{x, "i64"}
		if l.narrow == nil {
			l.narrow = map[string]string{}
		}
		l.narrow[x] = iv
	}
	l.loops = append(l.loops, s.Carried)
	err := l.stmts(s.Then)
	l.loops = l.loops[:len(l.loops)-1]
	end := l.env
	l.b, l.indent = saved, savedIndent
	if err != nil {
		return err
	}
	fn := "() -> ()"
	switch len(tys) {
	case 0:
	case 1:
		fn = "(i64) -> i64"
	default:
		fn = fmt.Sprintf("(%s) -> (%s)", strings.Join(tys, ", "), strings.Join(tys, ", "))
	}
	l.emit("%sebpf.loop %d unroll%s (%s) : %s {", resultDecl(res, len(s.Carried)), s.Count, bnd, strings.Join(inits, ", "), fn)
	l.emit("^bb0(%s):", strings.Join(append([]string{iv + ": i32"}, params...), ", "))
	l.b.WriteString(b.String())
	l.emit("  %s %s", yieldText("ebpf.loop.yield", s.Carried, end, tys), loc(s.Pos))
	l.emit("} %s", loc(s.Pos))
	l.env = pre
	l.bindResults(res, s.Carried, tys)
	return nil
}

func (l *lowerer) index32(x string, p Pos) string {
	if n, ok := l.narrow[x]; ok {
		return n
	}
	t := l.val()
	l.emit("%s = arith.trunci %s : i64 to i32 %s", t, x, loc(p))
	return t
}

func lowerFunc(b *strings.Builder, p *Program) error {
	if p.FRet == nil {
		return fmt.Errorf("internal: function %s has no value", p.Name)
	}
	n := 0
	l := &lowerer{b: b, n: &n, maps: map[*MapDecl]string{}, indent: "  ", env: map[string]ssaVal{}, refs: map[string]borrow{}, wins: map[string]borrow{}, kind: p.Kind}
	var syms, params, tys []string
	for i, a := range p.FParams {
		v := fmt.Sprintf("%%a%d", i)
		if i == p.FWin {
			t := fmt.Sprintf("!ebpf.pkt_window<%d>", p.FWinLen)
			l.wins[a] = borrow{v, int(p.FWinLen)}
			params = append(params, v+": "+t)
			tys = append(tys, t)
			continue
		}
		if i == p.FCtx {
			t := fmt.Sprintf("!ebpf.ctx<%q>", p.FCtxKind)
			l.kind = p.FCtxKind
			params = append(params, "%ctx: "+t)
			tys = append(tys, t)
			continue
		}
		if i == p.FBorrow {
			t := fmt.Sprintf("!ebpf.borrowed<%s>", valueType(p.FBorrowMap))
			l.refs[a] = borrow{v, p.FBorrowMap.ValueBits}
			params = append(params, v+": "+t)
			tys = append(tys, t)
			continue
		}
		l.env[a] = ssaVal{v, "i64"}
		params = append(params, v+": i64")
		tys = append(tys, "i64")
	}
	for i, m := range p.Maps {
		syms = append(syms, "@"+m.Name)
		l.maps[m] = fmt.Sprintf("%%m%d", i)
		params = append(params, fmt.Sprintf("%%m%d: %s", i, mapType(m)))
	}
	fmt.Fprintf(b, "ebpf.func @%s \"static\" (%s) -> i64", p.Name, strings.Join(tys, ", "))
	if len(syms) > 0 {
		fmt.Fprintf(b, " maps [%s]", strings.Join(syms, ", "))
	}
	b.WriteString(" {\n")
	fmt.Fprintf(b, "^bb0(%s):\n", strings.Join(params, ", "))
	if err := l.stmts(p.Body); err != nil {
		return err
	}
	r, err := l.expr(p.FRet)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "  ebpf.return %s : i64 %s\n", r.name, loc(p.VerdictPos))
	fmt.Fprintf(b, "} %s\n", loc(p.Pos))
	return nil
}
